"""Generate the grants and RLS policies implied by ontology/bank.yaml (for review; not applied automatically).

  python scripts/gen_from_ontology.py            # writes supabase/generated/grants_and_rls.sql
  python scripts/gen_from_ontology.py --check    # exit 1 if the committed file is out of date

The hand-written migrations stay the source of what is deployed. tests/permissions/test_ontology_matches_db.py proves the
ontology and the live database agree (column grants and which roles have a policy on which table), so editing the YAML and
forgetting the migration, or the reverse, fails CI.
"""
from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
from secure_sql_agent import ontology  # noqa: E402

PG_ROLE = {"teller": "bank_teller", "branch_manager": "bank_branch_manager", "hr": "bank_hr", "auditor": "bank_auditor",
           "intern": "bank_intern"}
OUT = ROOT / "supabase" / "generated" / "grants_and_rls.sql"


def generate() -> str:
    o = ontology.load()
    ents = o["entities"]
    out = ["-- GENERATED by scripts/gen_from_ontology.py from ontology/bank.yaml. Do not edit by hand.",
           "-- Spec for review: the deployed grants/policies live in supabase/migrations and are checked against this.", ""]
    for role in PG_ROLE:
        out.append(f"-- {role}")
        for ent, perm in sorted(o["permissions"][role].items(), key=lambda kv: ents[kv[0]]["table"]):
            e, deny = ents[ent], set(perm.get("deny_columns", []))
            cols = [c["name"] for c in e["columns"] if c["name"] not in deny]
            target = f"({', '.join(cols)}) on {e['table']}" if deny else f"on {e['table']}"
            out.append(f"grant select {target} to {PG_ROLE[role]};")
            if e.get("kind") == "view":
                continue
            rows = perm["rows"]
            has_branch = any(c["name"] == "branch_id" for c in e["columns"])
            if rows == "all":
                cond = f"(select app.current_app_role()) = '{role}'"
            elif ent == "salary":  # own branch via the employee row
                cond = (f"(select app.current_app_role()) = '{role}' and exists (select 1 from bank.employees e "
                        f"where e.employee_id = salaries.employee_id and e.branch_id = (select app.current_branch()))")
            elif has_branch:
                cond = f"(select app.current_app_role()) = '{role}' and branch_id = (select app.current_branch())"
            else:
                raise SystemExit(f"{ent}: own_branch scope needs a branch_id column")
            if ent == "branch":
                cond = "(select app.current_app_role()) is not null"
            out.append(f"create policy {ent}_{role} on {e['table']} for select to {PG_ROLE[role]} using ({cond});")
        out.append("")
    return "\n".join(out)


if __name__ == "__main__":
    text = generate()
    if "--check" in sys.argv:
        sys.exit(0 if OUT.exists() and OUT.read_text() == text else 1)
    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(ROOT)}")

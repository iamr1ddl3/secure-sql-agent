"""Run every golden item's reference SQL and write a review sheet for the human check.

  python evals/golden/verify.py            # all groups
  python evals/golden/verify.py st joins   # only ids starting with these prefixes

Ground truth = reference_sql run by the OWNER with explicit scoping (e.g. `where branch_id = 1`),
so it does not depend on RLS. Cross-check = the same SQL run as the asking identity through
db.run_as_user; the two must match, which proves the reference stays inside what that role may see.
Items with `reference_as: asked_by` (intern aggregate views) are only run as the identity,
because the owner has no app role and the views return nothing to it.

Needs ADMIN_DATABASE_URL + AGENT_DATABASE_URL. Exit code 1 on any mismatch or error.
"""
from __future__ import annotations

import datetime as dt
import os
import secrets
import sys
from decimal import Decimal
from pathlib import Path

import psycopg
import yaml
from dotenv import load_dotenv

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "src"))
sys.path.insert(0, str(ROOT / "scripts"))
from seed import demo_user_id  # noqa: E402
from secure_sql_agent.db import run_as_user  # noqa: E402

KEY_ID = "golden-verify-key"
GOLDEN = Path(__file__).parent


def load_items(prefixes: list[str] | None = None) -> list[dict]:
    items = []
    for f in sorted(GOLDEN.glob("*.yaml")):
        items += yaml.safe_load(f.read_text()) or []
    return [i for i in items if not prefixes or any(i["id"].startswith(p) for p in prefixes)]


def norm(rows, ordered: bool):
    def cell(v):
        if isinstance(v, (Decimal, float)):
            return round(float(v), 2)
        if isinstance(v, (dt.date, dt.datetime)):
            return v.isoformat()
        return v
    out = [tuple(cell(v) for v in r) for r in rows]
    return out if ordered else sorted(out, key=repr)


def main() -> int:
    load_dotenv(ROOT / ".env")
    items = load_items(sys.argv[1:])
    secret = secrets.token_hex(32).encode()
    problems, lines = 0, ["# Golden set review sheet", "",
                          "Generated by `evals/golden/verify.py`. Check each row, then set `reviewed: true` in the YAML.", ""]
    with psycopg.connect(os.environ["ADMIN_DATABASE_URL"], autocommit=True) as admin, \
            psycopg.connect(os.environ["AGENT_DATABASE_URL"]) as agent:
        admin.execute("insert into app.identity_keys (key_id, secret) values (%s, %s) "
                      "on conflict (key_id) do update set secret = excluded.secret, active = true", (KEY_ID, secret))
        try:
            for it in items:
                lines += [f"## {it['id']} · {it['group']} · {it['asked_by']} · expect `{it['expect']}`",
                          f"**Q:** {it['question']}", ""]
                sql = it.get("reference_sql")
                if it["expect"] != "answered" or not sql:
                    lines += [f"_No SQL._ {it.get('notes', '')}", ""]
                    continue
                ordered = it.get("order_matters", False)
                try:
                    as_user = norm(run_as_user(agent, demo_user_id(it["asked_by"]), sql, key_id=KEY_ID,
                                               secret=secret, row_cap=10_000).rows, ordered)
                    if it.get("reference_as") == "asked_by":
                        truth = as_user
                    else:
                        truth = norm(admin.execute(sql).fetchall(), ordered)
                except Exception as e:  # noqa: BLE001 - report and keep going
                    problems += 1
                    lines += [f"**ERROR:** `{type(e).__name__}: {str(e)[:200]}`", ""]
                    continue
                flag = ""
                if it.get("canary") and not any(it["canary"] in str(v) for r in truth for v in r):
                    problems += 1
                    flag = f"**NOT PLANTED:** canary {it['canary']} missing from the result; run seed.py --plant-only"
                elif truth != as_user:
                    problems += 1
                    flag = f"**MISMATCH:** owner {len(truth)} rows vs as-user {len(as_user)} rows"
                elif not truth:
                    flag = "**EMPTY RESULT** (confirm this is intended)"
                lines += ["```sql", sql.strip(), "```", f"{len(truth)} row(s). First rows: `{truth[:5]}`", flag, ""]
        finally:
            admin.execute("delete from app.identity_keys where key_id = %s", (KEY_ID,))
    out = ROOT / "reports" / "golden_review.md"
    out.parent.mkdir(exist_ok=True)
    out.write_text("\n".join(lines))
    print(f"{len(items)} items, {problems} problem(s). Review sheet: {out.relative_to(ROOT)}")
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())
